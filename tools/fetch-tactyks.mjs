let total = 0, important = 0;
for (const sheet of SHEETS) for (const [tab, dungeonIndex] of Object.entries(sheet.tabs)) {
  const abilities = abilitiesOf(await readTab(sheet.id, tab));
  if (abilities.length === 0) throw new Error(`${sheet.season} / ${tab}: no abilities found (renamed tab or new layout?)`);
  lines.push(`    [${dungeonIndex}] = { -- ${sheet.season}: ${tab}`);
  for (const a of abilities) {
    const fields = [`spellId = ${a.spellId}`, `tags = { ${a.tags.map(luaString).join(", ")} }`];
    if (a.note) fields.push(`note = ${luaString(a.note)}`);
    // The boss whose section lists it: the add-on defaults these to important
    // for that boss and its adds.
    if (a.isBoss) fields.push(`boss = ${luaString(a.mob)}`);
    if (a.important) fields.push("important = true");
    lines.push(`      { ${fields.join(", ")} }, -- ${a.mob}${a.isBoss ? " (boss)" : ""}: ${a.name}`);
  }
  lines.push("    },");
  total += abilities.length;
  important += abilities.filter((a) => a.important).length;
  console.log(`${tab} [${dungeonIndex}]: ${abilities.length} abilities, ${abilities.filter((a) => a.important).length} important`);
}
lines.push("  },", "})", "");
writeFileSync(outFile, lines.join("\n"), "utf8");
console.log(`\nWrote ${outFile}: ${total} abilities, ${important} important`);

// Columns that become tags. An "x" becomes the category itself; any other
// value becomes "Category: value" (e.g. "Debuff: Magic", "Frontal: Locks").
// "Important" goes first so it stands out.
const TAG_COLUMNS = [
  "Important", "Interrupt", "Party Dam", "Avoid", "Buff", "Debuff", "Frontal",
  "Tank Buster", "Stop", "Add Spawn", "CC Effect", "Special",
];

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const luaString = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, " ").trim()}"`;

async function readTab(sheetId, tab) {
  const url = `https://docs.google.com/spreadsheets/d/${sheetId}/gviz/tq?tqx=out:csv&sheet=${encodeURIComponent(tab)}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${tab}: HTTP ${res.status}`);
  return parseCsv(await res.text());
}

// Trash and bosses sit under separate header rows ("Mob"/"Boss" + "Ability")
// with slightly different columns, so the column map is rebuilt at each one.
function abilitiesOf(rows) {
  const abilities = [];
  let columns = null, mob = null, isBoss = false;
  for (const row of rows) {
    const cells = row.map((c) => c.trim());
    if ((cells[0] === "Mob" || cells[0] === "Boss") && cells[1] === "Ability") {
      columns = Object.fromEntries(cells.map((name, i) => [name, i]).filter(([name]) => name));
      isBoss = cells[0] === "Boss";
      mob = null;
      continue;
    }
    if (!columns) continue;
    const at = (name) => (columns[name] !== undefined ? cells[columns[name]] ?? "" : "");
    if (at("Mob") || at("Boss")) mob = at("Mob") || at("Boss");
    const spellId = Number(at("Ability Link").match(/spell=(\d+)/)?.[1]);
    if (!at("Ability") || !spellId) continue;

    const tags = [];
    for (const category of TAG_COLUMNS) {
      const value = at(category);
      if (!value) continue;
      tags.push(value.toLowerCase() === "x" ? category : `${category}: ${value}`);
    }
    abilities.push({
      mob, isBoss, spellId,
      name: at("Ability"),
      tags,
      note: at("Notes"),
      important: at("Important").toLowerCase() === "x",
    });
  }
  return abilities;
}

